#pragma once

#include <cstdint>
#include <string_view>

// as 0xRRGGBB: foreground, background, then ANSI black…white and their bright forms
struct ColorScheme {
    const char* key;
    const char* label;
    uint32_t fg, bg;
    uint32_t ansi[16];
};

